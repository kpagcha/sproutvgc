// Writes src/components/flaticons.generated.ts: the outlines of the Flaticon UIcons the app uses, read from the icon font
// the npm package ships (`@flaticon/flaticon-uicons`, its Regular Straight family, the one whose weight and square
// corners match Lucide's as main.css draws it), so the page draws a few small inline SVGs (`FlatIcon`) rather than
// loading the whole font. Free with attribution: the credits page credits them.
//
//   npm run flaticons                 regenerate the file from ICONS below
//   npm run flaticons -- --preview x  also draw every icon named in ICONS to x (a PNG), to look them over
//
// To add one, add its name (as the package's CSS names it, `fi-rs-<name>`) to ICONS and run it again.

import fs from 'node:fs'
import path from 'node:path'
import opentype from 'opentype.js'

/** The icons the app uses, by their name in the family. */
const ICONS = [
  'ban',
  'sun',
  'cloud-rain',
  'tornado',
  'snowflake',
  'model-cube-space',
  'wind',
  'shield',
  'shield-alt',
  'shield-plus',
  'handshake-angle',
  'story-fantasy',
] as const

const DIR = 'node_modules/@flaticon/flaticon-uicons/css/'
const FAMILY = 'regular-straight'
const OUT = 'src/components/flaticons.generated.ts'

const css = fs.readFileSync(path.join(DIR, 'regular/straight.css'), 'utf8')
const fontFile = fs.readdirSync(DIR).find((f) => f.startsWith(`uicons-${FAMILY}-`) && f.endsWith('.woff'))
if (!fontFile) throw new Error(`No ${FAMILY} font in ${DIR}`)
const buf = fs.readFileSync(path.join(DIR, fontFile))
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength))
const em = font.unitsPerEm

function codepointOf(name: string): number {
  const marker = `.fi-rs-${name}:before{content:"\\`
  const at = css.indexOf(marker)
  if (at < 0) throw new Error(`No icon fi-rs-${name}`)
  return parseInt(css.slice(at + marker.length, css.indexOf('"', at + marker.length)), 16)
}

/** Each icon's outline, in a square of the font's em, y down as SVG has it. */
const paths = Object.fromEntries(
  ICONS.map((name) => {
    const glyph = font.charToGlyph(String.fromCodePoint(codepointOf(name)))
    const p = glyph.getPath(0, font.ascender, em)
    if (process.argv.includes('--preview')) {
      const b = p.getBoundingBox()
      console.log(name, [b.x1, b.y1, b.x2, b.y2].map(Math.round).join(' '))
    }
    return [name, p.toPathData(2)]
  }),
)

const body = `// Generated by scripts/flaticons.ts (npm run flaticons) from @flaticon/flaticon-uicons' ${FAMILY} font: don't edit.
// Uicons by Flaticon (https://www.flaticon.com/uicons), free with attribution.

export const FLATICON_EM = ${em}

export const FLATICONS = {
${Object.entries(paths)
  .map(([n, d]) => `  '${n}': '${d}',`)
  .join('\n')}
} as const

export type FlaticonName = keyof typeof FLATICONS
`
fs.writeFileSync(OUT, body)
console.log(`Wrote ${ICONS.length} icons to ${OUT}`)

const preview = process.argv.indexOf('--preview')
if (preview >= 0) {
  const sharp = (await import('sharp')).default
  const S = 48
  const step = S + 40
  const svg =
    `<svg xmlns="http://www.w3.org/2000/svg" width="${ICONS.length * step}" height="${S + 28}">` +
    `<rect width="100%" height="100%" fill="#fff"/>` +
    ICONS.map(
      (n, i) =>
        `<g transform="translate(${i * step + 20},4) scale(${S / em})"><path d="${paths[n]}" fill="#111"/></g>` +
        `<text x="${i * step + 4}" y="${S + 22}" font-size="10" font-family="sans-serif">${n}</text>`,
    ).join('') +
    `</svg>`
  await sharp(Buffer.from(svg))
    .png()
    .toFile(process.argv[preview + 1])
}
